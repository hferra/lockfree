#pragma once

#include <thread>
#include <future>
#include <functional>
#include <concepts>
#include <immintrin.h> // Required for _mm_pause

#include "SPMCqueue.h"

// Define a C++20 concept to enforce your library's interface at compile-time
template<typename T>
concept WorkPolicy = requires(T policy) {
    { policy.Generate() } -> std::same_as<float>;
};

 /**
 * @brief Thread-isolated worker that executes a work-generation policy and publishes payloads to an SPMCQueue.
 *
 * @tparam Policy The compile-time user policy enforcing the WorkPolicy concept. Must implement a 
 *                thread-safe or thread-isolated `.Generate()` method returning a payload of type `T`.
 *
 * The SPMCProducer is designed to run inside a dedicated, isolated execution thread to inject 
 * work items into a supplied `SPMCQueue`. Payloads are generated by the compile-time `Policy` object,
 * avoiding runtime overhead. 
 *
 * @section Synchronization Strategy
 * Coordination with concurrent consumer threads is achieved entirely via the atomic `sequence` field 
 * embedded within each `Slot` of the ring buffer:
 * 
 * 1. **Generational Safety Check:** The producer maintains a strict local `count` of total items 
 *    published. Before writing to a physical slot, it samples its atomic sequence using `memory_order_acquire`. 
 *    If the sequence does not match the local `count`, the producer enters an active spin-wait state 
 *    (utilising `_mm_pause()`) until the slot is cleared by a consumer.
 * 
 * 2. **Symmetric Handshake Rollover:** Because the producer only overwrites slot values after the 
 *    underlying queue's circular buffer completely rotates, it is sufficient for a consumer to store 
 *    `reserved_ticket + RingBufferLen` into the slot's sequence field. This signals to the producer 
 *    that the data has been read and the slot can be safely overwritten on the next lap.
 * 
 * 3. **Data Availability Broadcast:** Once the payload is copied into the slot, the producer stores 
 *    `count + 1` into the sequence field using `memory_order_release`. This atomic release guarantee 
 *    ensures the payload data is fully visible in physical RAM before spinning consumers break out of 
 *    their respective turn-checks.
 *
 * @sa SPMCQueue
 * @sa WorkerPool
 */


template<WorkPolicy Policy, typename T>
class SPMCProducer
{
    private: 
    SPMCQueue<T>* queue;
    std::uint32_t count;
    static constexpr std::uint32_t rounds = 10000;

    public:
    SPMCProducer(SPMCQueue<T>* q)
    : queue(q)
    , count(0)
    {}

    // Compile-time template parameter accepts the raw closure type natively
    void Run(std::promise<std::uint32_t> output_promise, Policy& policy)
    {
        /*std::random_device rd;
        std::mt19937 gen(rd());
        std::uniform_real_distribution<float> dis(0.0f, 1.0f);*/

        constexpr std::uint32_t totalCount = RingBufferLen * rounds;
        
        for(std::uint32_t i = 0; i < totalCount; ++i)
        {
            float random_value = policy.Generate(); //dis(gen);
            
            // 1. Map our absolute sequence number to the physical array slot
            std::uint32_t slot_index = count % RingBufferLen;
            Slot<T>& target_slot = queue->store[slot_index];

            // 2. GENERATIONAL SAFETY BOUNDARY CHECK
            // Fetch the slot's current internal sequence ticket.
            std::uint32_t current_seq = target_slot.sequence.load(std::memory_order_acquire);

            // SPIN WAIT: Block if the slow worker thread has not updated it to our current turn target (current_seq != count).
            while (current_seq != count)
            {
                _mm_pause(); // Hint hardware pipelines during active polling loops
                current_seq = target_slot.sequence.load(std::memory_order_acquire);
            }

            // 3. SECURE PAYLOAD COMMIT
            // Direct implicit conversion via our zero-cost operator= wrapper
            target_slot = random_value; 

            // 4. TICKETING ADVANCEMENT HANDSHAKE
            // Advance the internal slot tracker to (count + 1). 
            // This signals to the spinning consumers that this specific slot data is fresh and ready.
            // memory_order_release guarantees the payload data is visible BEFORE the sequence shifts.
            target_slot.sequence.store(count + 1, std::memory_order_release);

            // 5. Publish global progress tracking boundary
            count++;
            queue->writeIdx.store(count, std::memory_order_release);
        }
        output_promise.set_value(totalCount);
    }
};